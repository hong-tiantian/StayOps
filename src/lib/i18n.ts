type WidenStrings<T> = {
  -readonly [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends (...args: infer Args) => infer Ret
      ? (...args: Args) => Ret
      : T[K] extends object
        ? WidenStrings<T[K]>
        : T[K];
};

type UiBundle = WidenStrings<typeof baseUi.en>;
type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends object ? DeepPartial<T[K]> : T[K];
};

function withLocale(overrides: DeepPartial<UiBundle>): UiBundle {
  return {
    ...baseUi.en,
    ...overrides,
    nav: { ...baseUi.en.nav, ...(overrides.nav ?? {}) },
    briefing: { ...baseUi.en.briefing, ...(overrides.briefing ?? {}) },
    booking: { ...baseUi.en.booking, ...(overrides.booking ?? {}) },
    freshness: { ...baseUi.en.freshness, ...(overrides.freshness ?? {}) },
    messages: { ...baseUi.en.messages, ...(overrides.messages ?? {}) },
    activity: { ...baseUi.en.activity, ...(overrides.activity ?? {}) },
    ledger: { ...baseUi.en.ledger, ...(overrides.ledger ?? {}) },
    task: {
      ...baseUi.en.task,
      ...(overrides.task ?? {}),
      columns: { ...baseUi.en.task.columns, ...(overrides.task?.columns ?? {}) },
    },
    recovery: { ...baseUi.en.recovery, ...(overrides.recovery ?? {}) },
    timeline: {
      ...baseUi.en.timeline,
      ...(overrides.timeline ?? {}),
      filters: { ...baseUi.en.timeline.filters, ...(overrides.timeline?.filters ?? {}) },
      chain: { ...baseUi.en.timeline.chain, ...(overrides.timeline?.chain ?? {}) },
    },
    status: { ...baseUi.en.status, ...(overrides.status ?? {}) },
  };
}

